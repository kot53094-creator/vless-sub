-- Карантин источников.
--
-- Автопоиск добавляет публичные подписки сам, без человека. Пока источник
-- не доказал, что даёт живые узлы, его серверы не должны попадать в
-- подписку людям: иначе случайная сборка мусора размывает пул и человек
-- видит «мёртвый VPN».
--
-- 1 — источник в карантине: sync его разбирает, узлы проверяются, но в
--     выдачу они не идут (фильтр в sub.ts и health.ts).
-- 0 — источник проверен: узлы участвуют в пуле.
--
-- Снимает карантин автоматика: три узла источника прошли проверку трафиком
-- за 72 часа. Так делает discover.ts после каждого sync.

ALTER TABLE sources ADD COLUMN quarantine INTEGER NOT NULL DEFAULT 0;

CREATE INDEX IF NOT EXISTS idx_sources_quarantine ON sources (quarantine);
