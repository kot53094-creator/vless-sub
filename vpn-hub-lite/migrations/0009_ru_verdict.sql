-- не отдаёт такой узел 48 часов — даже если TCP-проверка из Cloudflare и
-- американский раннер считают его живым. RU-мнение приоритетнее: человек
-- сидит именно там.
--
-- NULL — российского вердикта нет, узел оценивается по общим проверкам.

ALTER TABLE servers ADD COLUMN ru_dead_at TEXT;
