import { describe, expect, it } from "vitest";

import { replacementLine } from "../src/labels";

describe("отчёт о замене узла", () => {
  it("показывает страну умершего и страну замены", () => {
    expect(replacementLine("🇩🇪 Германия", ["🇫🇮 Финляндия"], 2)).toBe(
      "🇩🇪 Германия → 🇫🇮 Финляндия · 2 чел.",
    );
  });

  it("перечисляет несколько замен", () => {
    expect(replacementLine("🇳🇱 Нидерланды", ["🇸🇪 Швеция", "🇵🇱 Польша"], 3)).toBe(
      "🇳🇱 Нидерланды → 🇸🇪 Швеция, 🇵🇱 Польша · 3 чел.",
    );
  });

  it("честно пишет, если замены не нашлось", () => {
    expect(replacementLine("🇷🇺 Россия", [], 1)).toBe(
      "🇷🇺 Россия → замены не нашлось · 1 чел.",
    );
  });
});
